"""A workbook read as a workbook: coordinates, formulas, styles, tables, charts.

FrontierAgent's ``_reader_xlsx.py`` is the reference (audit D29-D45) and this is a port of
it, with one deliberate difference recorded in ``xlsx.py``'s own docstring: the grid is
tab-separated rather than a markdown pipe table, because ``normalize_for_quote_match``
folds whitespace away and keeps ``|``, so a quotation spanning two cells can verify against
one and never against the other. ``test_two_adjacent_cells_verify_as_one_quotation`` is
that difference, asserted rather than asserted-about.

Every fixture is generated by openpyxl here rather than committed: a binary in the tree is
a thing nobody can review in a diff.
"""
from __future__ import annotations

import datetime
import importlib

import pytest

from misaka.core.documents.office import xlsx

openpyxl = importlib.import_module("openpyxl")


def _book(tmp_path, name="book.xlsx"):
    from openpyxl import Workbook
    return Workbook(), str(tmp_path / name)


def _save(wb, path):
    wb.save(path)
    return path


# ── grid ────────────────────────────────────────────────────────────────────

def test_the_grid_carries_column_letters_and_row_numbers(tmp_path):
    wb, path = _book(tmp_path)
    ws = wb.active
    ws.title = "Revenue"
    ws["A1"], ws["B1"] = "year", "amount"
    ws["A2"], ws["B2"] = 2024, 1234
    out = xlsx.render(_save(wb, path))
    assert "## Sheet: Revenue" in out
    assert "\tA\tB" in out
    assert "1\tyear\tamount" in out
    assert "2\t2024\t1234" in out


def test_two_adjacent_cells_verify_as_one_quotation(tmp_path):
    """The reason the grid is not a markdown table. ``normalize_for_quote_match`` removes
    whitespace and keeps ``|``: under a pipe table "year amount" folds to "yearamount" and
    the page folds to "|year|amount|", so the quotation cannot be found. Tabs fold away."""
    from misaka.core.documents.index import normalize_for_quote_match

    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"], ws["B1"] = "year", "amount"
    page = xlsx.render(_save(wb, path))
    assert normalize_for_quote_match("year amount") in normalize_for_quote_match(page)


def test_an_empty_row_inside_a_region_is_dropped_but_numbering_is_real(tmp_path):
    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"], ws["A3"] = "top", "bottom"
    out = xlsx.render(_save(wb, path))
    assert "1\ttop" in out and "3\tbottom" in out
    assert "\n2\t" not in out


def test_two_data_islands_are_separated_and_labelled(tmp_path):
    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"] = "first"
    ws["A9"] = "second"          # a gap of more than _GAP blank rows splits the block
    out = xlsx.render(_save(wb, path))
    assert "`data region 1: A1`" in out
    assert "`data region 2: A9`" in out


# ── rendered values ─────────────────────────────────────────────────────────

@pytest.mark.parametrize(("value", "fmt", "shown"), [
    (datetime.datetime(2024, 3, 1), None, "2024-03-01"),  # noqa: DTZ001 - a cell has no zone
    (datetime.datetime(2024, 3, 1, 14, 30, 5), None, "2024-03-01 14:30:05"),  # noqa: DTZ001
    (0.153, "0.0%", "15.3%"),
    (1234567.0, "#,##0", "1,234,567"),
    (1234.5, '"$"#,##0.00', "$1,234.50"),
    (-1234.0, "#,##0;(#,##0)", "(1,234)"),
    (12345.0, "0.00E+00", "1.23E+04"),
    (1234567.0, '#,##0,,"M"', "1234567"),   # trailing-comma scaling is not rendered
])
def test_number_formats_render_the_way_the_sheet_shows_them(tmp_path, value, fmt, shown):
    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"] = value
    if fmt:
        ws["A1"].number_format = fmt
    assert shown in xlsx.render(_save(wb, path))


def test_a_number_format_is_recorded_once_at_sheet_level(tmp_path):
    wb, path = _book(tmp_path)
    ws = wb.active
    for row in range(1, 6):
        ws.cell(row=row, column=1, value=0.5).number_format = "0.0%"
    out = xlsx.render(_save(wb, path))
    assert "▸ number-format" in out
    assert "0.0% A1:A5" in out


