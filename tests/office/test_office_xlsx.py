def test_a_hidden_sheet_is_read_and_marked(tmp_path):
    """Owner decision D6: a hidden sheet is read. An archival workbook hides the sheet
    that holds the data more often than it hides junk, and missing data is the worse
    failure for a corpus. It is marked so a reader knows where the text came from."""
    wb, path = _book(tmp_path)
    wb.active["A1"] = "visible"
    hidden = wb.create_sheet("Workings")
    hidden["A1"] = "the number nobody meant to publish"
    hidden.sheet_state = "hidden"
    out = xlsx.render(_save(wb, path))
    assert "## Sheet: Workings (hidden)" in out
    assert "the number nobody meant to publish" in out


