def test_a_chart_title_split_across_runs_keeps_its_spaces_and_its_quotes(tmp_path):
    """``"".join`` over the title's text nodes runs words together, and a title carrying a
    quote closes the ``title="..."`` attribute early."""
    from openpyxl.chart import BarChart, Reference
    wb, path = _book(tmp_path)
    ws = wb.active
    ws.title = "D"
    ws.append(["q", "v"])
    for n in range(1, 4):
        ws.append([f"Q{n}", n])
    chart = BarChart()
    chart.title = 'Revenue "2024" by quarter'
    chart.add_data(Reference(ws, min_col=2, min_row=1, max_row=4), titles_from_data=True)
    ws.add_chart(chart, "D2")
    out = xlsx.render(_save(wb, path))
    assert "Revenue" in out and "by quarter" in out
    assert 'title="Revenue' in out
    assert out.count('title="') == 1        # the attribute was not closed early
