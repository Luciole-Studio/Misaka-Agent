# ── size guard ──────────────────────────────────────────────────────────────

def test_a_region_too_large_to_grid_degrades_to_its_reference(tmp_path, monkeypatch):
    """A dense island of a million cells is not rendered into the model's context; it is
    named, with the argument that fetches part of it."""
    monkeypatch.setattr(xlsx, "MAX_GRID_CELLS", 4)
    wb, path = _book(tmp_path)
    ws = wb.active
    for row in range(1, 4):
        for col in range(1, 4):
            ws.cell(row=row, column=col, value=row * col)
    out = xlsx.render(_save(wb, path))
    assert "cell_range" in out
    assert "A1:C3" in out


@pytest.mark.parametrize("rng", ["S!A:B", "S!2:3", "S!B"])
def test_a_whole_column_or_row_range_is_filled_from_the_sheet(tmp_path, rng):
    """openpyxl half-accepts these: ``range_boundaries`` returns None for the bound the
    argument did not give, which used to reach the grid and die on ``None + 1`` -- a bare
    TypeError out of a tool call, which a model cannot act on. FrontierAgent has the same
    crash. The missing bounds come from the sheet's extent, which is what was meant."""
    wb, path = _book(tmp_path)
    ws = wb.active
    ws.title = "S"
    for row in range(1, 5):
        ws.cell(row=row, column=1, value=f"a{row}")
        ws.cell(row=row, column=2, value=f"b{row}")
    out = xlsx.render(_save(wb, path), cell_range=rng)
    assert "`cell_range:" in out
    assert "\t" in out


