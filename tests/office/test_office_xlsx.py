# ── csv / tsv ───────────────────────────────────────────────────────────────

def test_a_csv_is_a_relational_table_with_column_meta(tmp_path):
    path = tmp_path / "rows.csv"
    body = "name,amount\n" + "".join(f"r{n},{n}\n" for n in range(1, 31))
    path.write_text(body, encoding="utf-8")
    out = xlsx.render_csv(str(path))
    assert "▸ table" in out
    assert "amount: num, min=1, max=30" in out
    assert "r30,30" in out           # csv is never truncated: paging is the layer above


def test_a_csv_line_verifies_exactly_as_the_file_writes_it(tmp_path):
    """A workbook has no textual form, so its grid can use tabs. A csv *is* text, and a
    reader quotes the line as it stands -- so the rows go back out through ``csv.writer``
    on the source dialect and round-trip, quoting included. Rendering them with tabs made
    ``verify_quote("North,800")`` fail against the file that literally contains it."""
    from misaka.core.documents.index import normalize_for_quote_match

    path = tmp_path / "regions.csv"
    path.write_text('region,units,note\nNorth,800,"a, with a comma"\nSouth,440,plain\n',
                    encoding="utf-8")
    out = xlsx.render_csv(str(path))
    folded = normalize_for_quote_match(out)
    assert normalize_for_quote_match("North,800") in folded
    assert normalize_for_quote_match('"a, with a comma"') in folded


def test_a_tsv_splits_on_tabs(tmp_path):
    path = tmp_path / "rows.tsv"
