def test_an_uncached_formula_inside_an_excel_table_is_marked_too(tmp_path):
    """The head promises "empty formula caches marked uncached". FrontierAgent's
    ``_x_table_regions`` takes no ``mark_uncached``, so inside an Excel Table the same cell
    renders as nothing at all -- and a blank cell reads as "this formula is empty"."""
    from openpyxl.worksheet.table import Table
    wb, path = _book(tmp_path)
    ws = wb.active
    ws.append(["name", "double"])
    for n in range(1, 4):
        ws.append([f"r{n}", f"=A{n + 1}"])
    ws.add_table(Table(displayName="T", ref="A1:B4"))
    out = xlsx.render(_save(wb, path))
    assert out.count("`uncached`") >= 3


def test_a_region_whose_cells_all_render_empty_is_not_announced(tmp_path):
    """``=IF(A1>0,A1,"")`` caches an empty string: non-empty to the coordinate scan, empty
    to the renderer. Announcing a region and then showing no rows asserts that something is
    there and says nothing about it."""
    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"], ws["B1"] = "", ""
    ws["A5"] = "real content"
    out = xlsx.render(_save(wb, path))
    assert "`data region" in out          # the real one survives
    assert "real content" in out
    assert "\tA\tB\n" not in out          # the all-empty one is not announced


def test_a_chart_whose_data_sheet_is_gone_is_still_reported(tmp_path):
    """A chart is filed under the sheet its data is on. When no worksheet claims that name
    -- an external reference, a deleted sheet -- FrontierAgent drops it silently: its
    fallback only catches the unparseable case."""
    wb, path = _book(tmp_path)
    wb.active["A1"] = "content"
    _save(wb, path)
    real = xlsx._chart_lines
    try:
        xlsx._chart_lines = lambda p: {"Ghost": ["bar series='Ghost'!$A$1:$A$4"]}
        out = xlsx.render(path)
    finally:
        xlsx._chart_lines = real
    assert "▸ charts" in out
    assert "Ghost" in out


def test_a_cell_range_point_query_does_not_scan_the_whole_workbook(tmp_path):
    """Asking for two cells must not walk every cell of every sheet -- which is also what
    decides whether a 90-second recalculation subprocess is worth starting."""
    wb, path = _book(tmp_path)
    ws = wb.active
    ws.title = "S"
    for row in range(1, 200):
        ws.cell(row=row, column=1, value=row)
    _save(wb, path)
    seen = []
    real = xlsx._has_formula
    try:
        xlsx._has_formula = lambda cell: seen.append(1) or real(cell)
        xlsx.render(path, cell_range="S!A1:A2")
    finally:
        xlsx._has_formula = real
    assert len(seen) <= 8          # the four cells of the range, twice over at worst


