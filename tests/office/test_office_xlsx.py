def test_a_formula_this_product_wrote_reads_back_as_uncached(tmp_path):
    """openpyxl cannot write a cached value, and neither can this product's writer: a
    workbook it produced has empty caches until something calculates them. Saying
    ``uncached`` is the honest answer -- a blank cell would read as "the formula is zero"."""
    wb, path = _book(tmp_path)
    ws = wb.active
    ws["A1"], ws["A2"] = 2, "=A1*3"
    out = xlsx.render(_save(wb, path))
    assert "`uncached`" in out
    assert "uncached" in out.split("## Sheet")[0]  # the head says why, once


