VERSION = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]


def schemaUrl(name: str) -> str:
    return f"https://raw.githubusercontent.com/Luciole-Studio/Misaka-Agent/v{VERSION}/misaka/schemas/{name}.schema.json"


def _rendered(name: str) -> dict:
    return json.loads(renderConfigSchemas()[f"misaka/schemas/{name}.schema.json"])


def _validator(name: str):
    schema = _rendered(name)
    return jsonschema.validators.validator_for(schema)(schema)


