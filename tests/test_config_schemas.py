def test_accepts_schema_in_settings_json_and_preserves_unknown_settings(tmp_path):
    (tmp_path / "settings.json").write_text(json.dumps({
        "$schema": schemaUrl("settings"), "theme": "light", "extensionSetting": {"enabled": True},
    }), encoding="utf-8")

    manager = SettingsManager.create(str(tmp_path), str(tmp_path))
    assert manager.getTheme() == "light"
    assert manager.getGlobalSettings()["$schema"] == schemaUrl("settings")
    assert manager.getGlobalSettings()["extensionSetting"] == {"enabled": True}

    # A write keeps both.
    manager.setTheme("dark")
    written = json.loads((tmp_path / "settings.json").read_text(encoding="utf-8"))
    assert written == {"$schema": schemaUrl("settings"), "theme": "dark", "extensionSetting": {"enabled": True}}


def test_a_roles_settings_json_keeps_schema_through_a_role_write(tmp_path):
    # MISAKA fork: a role's own settings.json is written by the manager itself (ROLE_KEYS).
    home = tmp_path / "home"
    home.mkdir()
    role = tmp_path / "role"
    role.mkdir()
    (role / "settings.json").write_text(json.dumps({"$schema": schemaUrl("settings"), "defaultThinkingLevel": "low"}),
                                        encoding="utf-8")

    manager = SettingsManager.create(str(tmp_path), str(home), {"projectTrusted": False})
    manager.bindRole(str(role))
    assert manager.getRoleThinkingLevel() == "low"
    manager.setDefaultThinkingLevel("high")

    written = json.loads((role / "settings.json").read_text(encoding="utf-8"))
    assert written == {"$schema": schemaUrl("settings"), "defaultThinkingLevel": "high"}
    assert not (home / "settings.json").exists()


